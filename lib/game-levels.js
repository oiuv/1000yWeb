// Keep Delphi integer division and its large-experience truncation order.
function gameLevel(experience) {
  if (experience <= 0) return 100;
  if (experience >= 1085138172) return 9999;
  for (let i = 1; i < LEVELS.length; i++) {
    if (experience < LEVELS[i][0]) {
      const [start, gap] = LEVELS[i - 1];
      const remainder = experience - start;
      const fraction = start < 10000000
        ? Math.trunc(remainder * 100 / gap)
        : Math.trunc(Math.trunc(remainder / 100) * 100 / Math.trunc(gap / 100));
      return i * 100 + fraction;
    }
  }
  return 9999;
}
